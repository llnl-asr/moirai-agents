def _files(root, exts):
    for dp, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d not in {".git", "__pycache__", "build", ".venv", "venv"}]
        for f in fn:
            if Path(f).suffix.lower() in exts:
                yield Path(dp) / f


def _scan_py(path, rel):
    try:
        tree = ast.parse(path.read_text(errors="replace"))
    except SyntaxError as e:
        return [{"file": rel, "line": e.lineno, "call": "(does not parse)", "function": ""}]
    out = []

    def walk(node, fn):
        for ch in ast.iter_child_nodes(node):
            cur = fn
            if isinstance(ch, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                cur = f"{fn}.{ch.name}" if fn else ch.name
            if isinstance(ch, ast.Call):
                name = ch.func.attr if isinstance(ch.func, ast.Attribute) else getattr(ch.func, "id", "")
                if name in PY_IO:
                    arg = ast.unparse(ch.args[0])[:80] if ch.args else ""
                    out.append({"file": rel, "line": ch.lineno, "call": name, "kind": PY_IO[name], "function": fn, "argument": arg})
            walk(ch, cur)
    walk(tree, "")
    return out


def _blank(src):
    """Comments and strings become spaces (same offsets), so braces and names can be matched on code only."""
    pat = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'', re.S)
    return pat.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), src)


def _c_function(code, fname):
    """Offset just after the opening brace of fname's definition, or -1."""
    pat = re.compile(r"(?m)^[ \t]*(?:[\w:*&<>,~]+[ \t*&]+)+(?:[\w:]*::)?" + re.escape(fname) + r"\s*\(([^;{}]*)\)\s*(?:const\s*)?(?:noexcept\s*)?(?:override\s*)?\{")
    m = pat.search(code)
    return m.end() if m else -1


def _scan_c(path, rel):
    code = _blank(path.read_text(errors="replace"))
    funcs = [(m.start(), m.group(1)) for m in re.finditer(r"(?m)^[\w:*&<>,~ \t]+?\b([A-Za-z_]\w*)\s*\([^;{}]*\)\s*\{", code)]
    out = []
    for m in C_IO.finditer(code):
        fn = ""
        for pos, name in funcs:
            if pos <= m.start():
                fn = name
        out.append({"file": rel, "line": code.count("\n", 0, m.start()) + 1, "call": m.group(1), "function": fn})
    return out


def _py_lambda(expr, params):
    names = {n.id for n in ast.walk(ast.parse(expr, mode="eval")) if isinstance(n, ast.Name)} - set(dir(builtins))
    use = sorted(names & (set(params) | {"result"}))
    return "lambda " + "".join(f"{n}=None, " for n in use) + f"**_: {expr}"


def _items(acts, params):
    rows = []
    for e in acts:
        key = _py_lambda(e["key_expr"], params) if e.get("key_expr") else repr(str(e.get("key", "")))
        uri = _py_lambda(e["uri_expr"], params) if e.get("uri_expr") else (repr(e["uri"]) if e.get("uri") else key)
        rows.append(f"({e['type']!r}, {key}, {e.get('store', 'local_disk').upper()!r}, {uri})")
    return "[" + ", ".join(rows) + "]"


def _find_py(tree, qual):
    node, parts = tree, qual.split(".")
    for name in parts:
        node = next((c for c in ast.walk(node) if isinstance(c, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and c.name == name), None)
        if node is None:
            return None
    return node


def _apply_py(path, acts):
    src = path.read_text()
    tree, lines = ast.parse(src), src.split("\n")
    edits, missing = [], []
    for a in acts:
        node = _find_py(tree, a["function"])
        if node is None:
            missing.append(a["function"])
            continue
        at = min([d.lineno for d in node.decorator_list] + [node.lineno]) - 1
        ind = lines[node.lineno - 1][:len(lines[node.lineno - 1]) - len(lines[node.lineno - 1].lstrip())]
        params = [x.arg for x in node.args.posonlyargs + node.args.args + node.args.kwonlyargs]
        deco = f"{ind}@_moirai_prov.activity({a['name']!r}, used={_items(a.get('used', []), params)}, generated={_items(a.get('generated', []), params)})"
        edits.append((at, deco))
    for at, text in sorted(edits, reverse=True):
        lines.insert(at, text)
    first = 0
    if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(getattr(tree.body[0], "value", None), ast.Constant):
        first = tree.body[0].end_lineno
    for n in tree.body:
        if isinstance(n, ast.ImportFrom) and n.module == "__future__":
            first = n.end_lineno
    lines.insert(first + len([1 for at, _ in edits if at < first]), "import _moirai_prov  # moirai-agents")
    path.write_text("\n".join(lines))
    return missing


def _c_lit(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _c_entity(e, key="key"):
    k = e.get("key_expr") or _c_lit(e.get("key", ""))
    uri = e.get("uri_expr") or (_c_lit(e["uri"]) if e.get("uri") else k)
    return k, f"MOIRAI_STORE_{e.get('store', 'local_disk').upper()}", uri


def _apply_c(path, acts, entry, types, cpp):
    src = path.read_text()
    inserts, missing = [], []
    code = _blank(src)
    for a in acts:
        at = _c_function(code, a["function"].split("::")[-1])
        if at < 0:
            missing.append(a["function"])
            continue
        n = re.sub(r"\W", "_", a["name"])
        body = []
        if cpp:
            body.append(f"MOIRAI_CPP_ACTIVITY({n});")
            for verb, key in (("uses", "used"), ("generates", "generated")):
                for e in a.get(key, []):
                    k, st, uri = _c_entity(e)
                    body.append(f"moirai_{n}.{verb}({_c_lit(e['type'])}, {k}, {st}, {uri});")
        else:
            body.append(f"MOIRAI_C_ACTIVITY_START({n});")
            for rel, key in (("MOIRAI_REL_USED", "used"), ("MOIRAI_REL_GENERATED", "generated")):
                for e in a.get(key, []):
                    k, st, uri = _c_entity(e)
                    body.append(f"moirai_activity_relate_entity(moirai_{n}, {rel}, {_c_lit(e['type'])}, {k}, {st}, {uri});")
        inserts.append((at, "\n  " + "\n  ".join(body)))
    if entry:
        at = _c_function(code, "main")
        if at < 0:
            missing.append("main")
        else:
            body = ["moirai::initialize();" if cpp else "moirai_initialize(NULL);", "atexit(moirai_finalize);"]
            for t in types:
                role = "MOIRAI_ROLE_" + t["role"].upper()
                body.append(f"moirai_entity_type({_c_lit(t['type'])}, {role}, {_c_lit(t.get('description', ''))});")
            inserts.append((at, "\n  " + "\n  ".join(body)))
    for at, text in sorted(inserts, reverse=True):
        src = src[:at] + text + src[at:]
    head = "#include <moirai/moirai.hpp>\n#include <stdlib.h>\n" if cpp else "#include <moirai/moirai.h>\n#include <stdlib.h>\n"
    path.write_text(head + src)
    return missing


def _diff(src, dst):
    out = []
    for f in sorted(_files(dst, {".py", ".c", ".cc", ".cpp", ".cxx"})):
        rel = f.relative_to(dst)
        old = src / rel
        if rel.name == "_moirai_prov.py":
            continue
        a = old.read_text(errors="replace").splitlines(True) if old.exists() else []
        b = f.read_text(errors="replace").splitlines(True)
        if a != b:
            out.extend(difflib.unified_diff(a, b, f"a/{rel}", f"b/{rel}", n=1))
    return "".join(out)


def register(mcp):
    @mcp.tool()
    def annotate_scan(pipeline: str, limit: int = 300) -> dict:
        """Find every place the application touches data (open, load, save, HDF5, MPI-IO, ...) with file, line and function. Use first in the annotate
        stage, then read those functions to decide the entity types and activities. Returns {count, candidates: [{file, line, call, function}]}."""
        root = Path(P.load(pipeline)["source"])
        out = []
        for f in _files(root, {".py"}):
            out += _scan_py(f, str(f.relative_to(root)))
        for f in _files(root, {".c", ".cc", ".cpp", ".cxx"}):
            out += _scan_c(f, str(f.relative_to(root)))
        P.record(pipeline, STAGE, status="running", outputs={"candidates": len(out)}, note=f"scanned: {len(out)} data accesses")
        return {"count": len(out), "candidates": out[:limit]}

    @mcp.tool()
    def annotate_spec(pipeline: str, spec: dict) -> dict:
        """Check and save the provenance spec. Use after agreeing it with the user. spec: {entity_types: [{type, role, description}], activities: [{file,
        function, name, used: [{type, key|key_expr, store, uri|uri_expr}], generated: [...]}], entry: file with main (C/C++)}. role: input|output|intermediate|
        parameter|reference. store: local_disk|parallel_fs|memory|... key_expr: code over the function's parameters (Python: also `result`). Returns {status, problems}."""
        spec = json.loads(spec) if isinstance(spec, str) else spec
        root, bad = Path(P.load(pipeline)["source"]), []
        types = {t.get("type"): t for t in spec.get("entity_types", [])}
        for t, d in types.items():
            if d.get("role") not in ROLES:
                bad.append(f"type {t}: role must be one of {sorted(ROLES)}")
            if not d.get("description"):
                bad.append(f"type {t}: needs a description: readers of the graph depend on it")
        for a in spec.get("activities", []):
            where = f"activity {a.get('name')}"
            if not (root / a.get("file", "")).is_file():
                bad.append(f"{where}: no file {a.get('file')}")
            if not (a.get("used") or a.get("generated")):
                bad.append(f"{where}: relates no entity")
            for e in a.get("used", []) + a.get("generated", []):
                if e.get("type") not in types:
                    bad.append(f"{where}: undeclared type {e.get('type')}")
                if e.get("store", "local_disk") not in STORES:
                    bad.append(f"{where}: store must be one of {sorted(STORES)}")
                if not (e.get("key") or e.get("key_expr")):
                    bad.append(f"{where}: entity {e.get('type')} needs key or key_expr")
        if not spec.get("activities"):
            bad.append("the spec has no activity")
        if bad:
            return {"status": "error", "problems": bad}
        (P.pdir(pipeline) / "spec.json").write_text(json.dumps(spec, indent=1))
        P.record(pipeline, STAGE, outputs={"spec": spec, "summary": f"{len(types)} entity type(s), {len(spec['activities'])} activities"})
        return {"status": "ok", "entity_types": len(types), "activities": len(spec["activities"])}

    @mcp.tool()
    def annotate_apply(pipeline: str) -> dict:
        """Copy the app to <pipeline>/annotated and insert the saved spec. Use after annotate_spec; safe to repeat (it starts over from the source).
        Returns {status, annotated, files, missing, diff}."""
        c = P.load(pipeline)
        spec = P.stage(c, STAGE)["outputs"].get("spec")
        if not spec:
            return {"status": "error", "error": "no spec: call annotate_spec first"}
        session_src = (P.stage(c, "smoke")["outputs"].get("session_paths") or {}).get("source")
        src, dst = Path(session_src or c["source"]), P.pdir(pipeline) / "annotated"
        shutil.rmtree(dst, ignore_errors=True)
        shutil.copytree(src, dst, ignore=SKIP, symlinks=True)
        by_file, missing = {}, []
        for a in spec["activities"]:
            by_file.setdefault(a["file"], []).append(a)
        entry = spec.get("entry", "")
        if entry:
            by_file.setdefault(entry, [])
        python = False
        for rel, acts in by_file.items():
            f = dst / rel
            if f.suffix == ".py":
                python = True
                missing += _apply_py(f, acts)
            else:
                missing += _apply_c(f, acts, rel == entry, spec["entity_types"], f.suffix != ".c")
        if python:
            rows = [(t["type"], t["role"].upper(), t.get("description", "")) for t in spec["entity_types"]]
            (dst / "_moirai_prov.py").write_text(HELPER % json.dumps(rows))
        diff = _diff(src, dst)
        (P.pdir(pipeline) / "annotation.diff").write_text(diff)
        P.record(pipeline, STAGE, outputs={"annotated": str(dst), "files": sorted(by_file), "missing": missing, "languages": ["python"] if python else ["c"]},
                 note=f"annotated {len(by_file)} file(s)")
        return {"status": "ok" if not missing else "error", "annotated": str(dst), "files": sorted(by_file), "missing": missing, "diff": diff[:12000]}

    @mcp.tool()
    def annotate_validate(pipeline: str) -> dict:
        """Validate the annotation: every function was found, each file still compiles, every activity is in the code, every entity type is used, and the
        user's source is unchanged. Use after annotate_apply. Returns the verdict {status, failed, unknown, passed, total}."""
        c = P.load(pipeline)
        o = P.stage(c, STAGE)["outputs"]
        v = P.Verdict(STAGE)
        if not v.check("applied", bool(o.get("annotated")), "annotate_apply has not run", "run annotate_apply"):
            return P.finish_validation(pipeline, v)
        spec, dst = o["spec"], Path(o["annotated"])
        v.check("functions_found", not o.get("missing"), f"not found: {o.get('missing')}", "fix function names in the spec (Class.method for Python)")
        m = M.locate()
        for rel in o["files"]:
            f = dst / rel
            if f.suffix == ".py":
                try:
                    ast.parse(f.read_text())
                    v.check(f"parses:{rel}", True)
                except SyntaxError as e:
                    v.check(f"parses:{rel}", False, f"line {e.lineno}: {e.msg}", "fix the spec's key_expr")
            elif m.get("include"):
                cc = "gcc" if f.suffix == ".c" else "g++"
                r = subprocess.run([cc, "-fsyntax-only", f"-I{m['include']}", f"-I{m['dft_include']}", f"-I{f.parent}", str(f)], capture_output=True, text=True, timeout=120)
                errs = [ln for ln in r.stderr.splitlines() if "error" in ln and "moirai" in ln.lower()]
                if r.returncode and not errs:
                    v.inconclusive(f"compiles:{rel}", f"errors unrelated to moirai (build flags missing here): {r.stderr[:200]}")
                else:
                    v.check(f"compiles:{rel}", not errs, "; ".join(errs)[:300], "correct the key_expr or the function in the spec")
            else:
                v.inconclusive(f"compiles:{rel}", "moirai headers not found")
        text = "\n".join(p.read_text(errors="replace") for p in _files(dst, {".py", ".c", ".cc", ".cpp", ".cxx"}) if p.name != "_moirai_prov.py")
        for a in spec["activities"]:
            n = re.sub(r"\W", "_", a["name"])
            v.check(f"inserted:{a['name']}", repr(a["name"]) in text or n in text, "not in the annotated code", "re-run annotate_apply")
        used = {e["type"] for a in spec["activities"] for e in a.get("used", []) + a.get("generated", [])}
        unused = sorted({t["type"] for t in spec["entity_types"]} - used)
        v.check("types_used", not unused, f"never used: {unused}", "relate them to an activity or drop them")
        v.check("has_output", any(t["role"] == "output" for t in spec["entity_types"]), "no entity type is an output", "the scientific artifact must be an output")
        if not P.stage(c, "smoke")["outputs"].get("outputs_created"):
            v.inconclusive("coverage", "the smoke stage listed no output files to compare the spec against")
        return P.finish_validation(pipeline, v)
