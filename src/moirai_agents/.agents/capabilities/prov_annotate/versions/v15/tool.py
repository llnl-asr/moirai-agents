def _text(value, names):
    return str(value(**names) if callable(value) else value)


def _ok(when, names):
    return when is None or bool(when(**names) if callable(when) else when)


def _entity(item, names):
    etype, key, store, uri = item[:4]
    return (etype, _text(key, names), getattr(moirai.Store, store), _text(uri, names))


def _bind(act, relation, items, names):
    """Relate each entity of items to the activity, unless its optional `when` is false."""
    for item in items:
        if _ok(item[4] if len(item) > 4 else None, names):
            e = _entity(item, names)
            act.relate(relation, e)
            if len(item) > 5 and item[5]:
                _attrs(e, item[5], names)


def _after(act, generated, invalidated, updated, relations, names):
    for relation, items in (("GENERATED", generated), ("INVALIDATED", invalidated), ("UPDATED", updated)):
        _bind(act, getattr(moirai.Relation, relation), items, names)
    for relation, subject, obj, when in relations:
        if _ok(when, names):
            moirai.relate(getattr(moirai.Relation, relation), _entity(subject, names), _entity(obj, names))


# ---- inputs, outputs and attributes, each one value its own small entity "name=value" (the trace keeps a uri of at most ~250 characters
# and replaces quotes, brackets and the like): an activity used its "<activity>.input" entities (its parameters) and generated its
# "<activity>.output" entities (what it returned, and the values named by capture.outputs); an entity's "<type>.attribute" entities are part_of it.
# Capturing never raises into the app.
_FLAG = re.compile(r"(^|\\s)--?[A-Za-z]")
MAX_VALUES = 48


def _flags(s):
    """--name value, --name=value and -x value pairs of a command line."""
    try:
        toks = shlex.split(s)
    except ValueError:
        toks = s.split()
    out, i = {}, 0
    num = lambda t: t.lstrip("-").replace(".", "", 1).isdigit()
    while i < len(toks):
        t = toks[i]
        if len(t) > 1 and t[0] == "-" and not num(t):
            k, v = t.lstrip("-"), "true"
            if "=" in k:
                k, v = k.split("=", 1)
            elif i + 1 < len(toks) and not (toks[i + 1][:1] == "-" and not num(toks[i + 1])):
                v, i = toks[i + 1], i + 1
            out[("--" if len(k) > 1 else "-") + k] = v
        i += 1
    return out


def _summ(v, depth=0):
    """A plain summary: values as they are, containers shallowly, arrays by shape, objects by their own attributes (two levels)."""
    if v is None or isinstance(v, (bool, int, float, str)):
        return v
    if isinstance(v, (bytes, bytearray)):
        return {"type": "bytes", "len": len(v)}
    if isinstance(v, os.PathLike):
        return os.fspath(v)
    if isinstance(v, (list, tuple, set, frozenset)):
        v = list(v)
        return [_summ(x, depth + 1) for x in v] if depth < 3 and len(v) <= 16 else {"len": len(v)}
    if isinstance(v, dict):
        return {str(k): _summ(x, depth + 1) for k, x in list(v.items())[:32]} if depth < 3 else {"len": len(v)}
    shape = getattr(v, "shape", None)
    if shape is not None and not callable(shape):
        try:
            return {"shape": "x".join(str(int(x)) for x in shape), **({"dtype": str(v.dtype)} if hasattr(v, "dtype") else {})}
        except (TypeError, ValueError):
            return {"type": type(v).__name__}
    if depth < 2 and hasattr(v, "__dict__") and not inspect.ismodule(v) and not callable(v):
        return {k: _summ(x, depth + 1) for k, x in list(vars(v).items())[:48] if not k.startswith("__") and not callable(x) and not inspect.ismodule(x)}
    return {"type": type(v).__name__}


def _pairs(v, path, out, flags):
    """name -> value text: scalars by their dotted path; a command line also gives its flags; lists of scalars joined with commas."""
    if isinstance(v, dict):
        for k, x in v.items():
            _pairs(x, f"{path}.{k}" if path else str(k), out, flags)
    elif isinstance(v, list) and all(not isinstance(x, (dict, list)) for x in v):
        out[path] = ",".join(str(x) for x in v)
    elif isinstance(v, list):
        for i, x in enumerate(v):
            _pairs(x, f"{path}[{i}]", out, flags)
    else:
        if isinstance(v, str) and " " in v and _FLAG.search(v):
            flags.update(_flags(v))
        out[path] = "" if v is None else str(v)


def _value_entities(etype, role, description, pairs):
    """One entity per name=value (at most MAX_VALUES)."""
    if etype not in _declared:
        _declared.add(etype)
        moirai.entity_type(etype, getattr(moirai.Role, role), description)
    out = []
    for k, v in list(pairs.items())[:MAX_VALUES]:
        text = f"{k}={v}"
        if len(text) > 240:
            text = text[:237] + "..."
        out.append((etype, hashlib.sha1((etype + text).encode()).hexdigest()[:16], moirai.Store.MEMORY, text))
    return out


def _collect(named, auto_names):
    flags, values, args = {}, {}, {}
    for label, v in named.items():
        _pairs(_summ(v), label, values, flags)
    for k, v in (auto_names or {}).items():
        _pairs(_summ(v), k, args, flags)
    out = dict(flags)                               # flags first: the knobs of a command line
    out.update({k: v for k, v in values.items() if k not in out})
    out.update({k: v for k, v in args.items() if k not in out and len(v) <= 200 and not k.endswith(".type")})
    return out


def _inputs(act, name, capture, names):
    try:
        named = {}
        for label, fn in (capture.get("inputs") or {}).items():
            try:
                named[label] = fn(**names) if callable(fn) else fn
            except Exception as e:                   # an input that cannot be read is recorded as such, never raised
                named[label] = "unreadable: " + type(e).__name__
        pairs = _collect(named, names if capture.get("auto", True) else {})
        for e in _value_entities(name + ".input", "PARAMETER", "A parameter of activity " + name + ": an argument (with its default), an attribute of the object "
                                 "it runs on, a flag of a command line, or a named value; its uri is name=value.", pairs):
            act.relate(moirai.Relation.USED, e)
    except Exception:
        pass


def _emit_outputs(act, name, pairs):
    """The activity generated one "<activity>.output" entity per name=value."""
    for e in _value_entities(name + ".output", "INTERMEDIATE", "What activity " + name + " returned, or recorded as named outputs (capture.outputs): "
                             "a result a hook keeps on self; its uri is name=value.", pairs):
        act.relate(moirai.Relation.GENERATED, e)


def _output(act, name, capture, result):
    try:
        if capture.get("output", True) and result is not None:
            pairs = {}
            _pairs(_summ(result), "value", pairs, {})
            _emit_outputs(act, name, pairs)
    except Exception:
        pass


def _outputs(act, name, capture, names):
    """capture.outputs {label: expression}: evaluated AFTER the call over `names` (the call's arguments, self, result; for a statement its locals), for a
    hook that returns None and keeps its result on self. One output entity per label, in addition to the return value; a label that raises is skipped."""
    try:
        pairs = {}
        for label, fn in (capture.get("outputs") or {}).items():
            try:
                _pairs(_summ(fn(**names) if callable(fn) else fn), label, pairs, {})
            except Exception:                        # an output that cannot be read is left out, never raised
                continue
        if pairs:
            _emit_outputs(act, name, pairs)
    except Exception:
        pass


def _attrs(entity, attrs, names):
    """An entity's attributes, each its own entity part_of it."""
    try:
        named = {}
        for label, fn in attrs.items():
            try:
                named[label] = fn(**names) if callable(fn) else fn
            except Exception as e:
                named[label] = "unreadable: " + type(e).__name__
        pairs = {}
        for label, v in named.items():
            _pairs(_summ(v), label, pairs, {})
        for a in _value_entities(entity[0] + ".attribute", "REFERENCE", "An attribute of a " + entity[0] + " entity; its uri is name=value.", pairs):
            moirai.relate(moirai.Relation.PART_OF, a, entity)
    except Exception:
        pass


def activity(name, used=(), generated=(), invalidated=(), updated=(), relations=(), signature=None, capture=None):
    """One moirai activity around each call; entity keys may read the call's arguments, and `result`. signature: the function whose
    parameters name the arguments, for a wrapper that takes *args. capture: {auto: record every argument (default on), output: record
    the return value (default on), inputs: {label: expression of the arguments}, outputs: {label: expression of the arguments, self and result,
    evaluated after the call}}."""
    capture = {} if capture is None else capture
    def wrap(fn):
        sig = inspect.signature(signature or fn)

        @functools.wraps(fn)
        def call(*a, **k):
            start()
            try:
                b = sig.bind(*a, **k)
                b.apply_defaults()
                names = dict(b.arguments)
            except TypeError:
                names = {}
            with moirai.Activity(name) as act:
                _bind(act, moirai.Relation.USED, used, names)
                _inputs(act, name, capture, names)
                result = fn(*a, **k)
                done = {**names, "result": result}
                _after(act, generated, invalidated, updated, relations, done)
                _output(act, name, capture, result)
                _outputs(act, name, capture, done)
                return result
        return call
    return wrap


def event(name, used=(), generated=(), invalidated=(), updated=(), relations=(), capture=None):
    """A one-shot activity at a statement; its keys are closures over the surrounding locals. It has no duration. capture: {inputs: {label: closure},
    outputs: {label: closure}}."""
    start()
    with moirai.Activity(name) as act:
        _bind(act, moirai.Relation.USED, used, {})
        _inputs(act, name, {"auto": False, **(capture or {})}, {})
        _after(act, generated, invalidated, updated, relations, {})
        _outputs(act, name, capture or {}, {})
