def _helper_checks(v, o, work, src=None, maestro="", maestro_args=""):
    """The annotation checks shared by annotate_validate and annotate_validate_preview. Adds to v; returns the deferred notes: checks that
    belong to a later stage, which are reported and never counted in this stage's verdict. src: the source root, to compare a YAML with."""
    spec, dst = o["spec"], Path(o["annotated"])
    deferred = []
    v.check("functions_found", not o.get("missing"), f"not found: {o.get('missing')}", "fix function names in the spec (Class.method for Python); for patch, subclass and statement fix target, base, anchor, in or params; for yaml_step fix step, or the texts it names")
    v.check("names_resolve", not o.get("unresolved"), "; ".join(o.get("unresolved") or [])[:600], "use a parameter, `result`, a module-level name of that file, or move the anchor; for yaml_step use a Maestro variable the study defines or uses, a $(step.workspace) of an ancestor step, a shell variable the cmd assigns, or list it under params / shell_vars")
    m = M.locate() if any(Path(rel).suffix.lower() not in ({".py"} | YAML_EXT) for rel in o["files"]) else {}
    for rel in o["files"]:
        f = dst / rel
        if f.suffix == ".py":
            try:
                ast.parse(f.read_text())
                v.check(f"parses:{rel}", True)
            except SyntaxError as e:
                v.check(f"parses:{rel}", False, f"line {e.lineno}: {e.msg}", "fix the spec's key_expr")
        elif f.suffix.lower() in YAML_EXT:
            _yaml_checks(v, rel, f, (Path(src) / rel) if src else None, dst, work, maestro, maestro_args)
        elif m.get("include"):
            cc = "gcc" if f.suffix == ".c" else "g++"
            r = subprocess.run([cc, "-fsyntax-only", f"-I{m['include']}", f"-I{m['dft_include']}", f"-I{f.parent}", str(f)], capture_output=True, text=True, timeout=120)
            errs = [ln for ln in r.stderr.splitlines() if "error" in ln and "moirai" in ln.lower()]
            if r.returncode and not errs:
                v.inconclusive(f"compiles:{rel}", f"errors unrelated to moirai (build flags missing here): {r.stderr[:200]}")
            else:
                v.check(f"compiles:{rel}", not errs, "; ".join(errs)[:300], "correct the key_expr or the function in the spec")
        else:
            v.inconclusive(f"compiles:{rel}", "moirai headers not found")
    if any(Path(rel).suffix == ".py" or Path(rel).suffix.lower() in YAML_EXT for rel in o["files"]):
        helpers = [p for p in _files(dst, {".py"}) if p.name == "_moirai_prov.py"]
        v.check("helper_single", len(helpers) == 1 and helpers[0].parent == dst, f"found {[str(p.relative_to(dst)) for p in helpers]}",
                "one _moirai_prov.py at the annotated root: modules import it by absolute name; re-run annotate_apply")
        env = Path(work) / "moirai_env.sh"
        if env.is_file():
            v.check("helper_on_pythonpath", str(dst) in env.read_text(), f"{env} does not export PYTHONPATH with {dst}", "integrate_apply must export PYTHONPATH=<annotated root>; re-run it")
        else:
            deferred.append({"name": "helper_on_pythonpath", "owner_stage": "integrate", "enforced_by": "integrate_validate: env_pythonpath and env_import",
                             "detail": "integrate has not written moirai_env.sh yet; it must export PYTHONPATH=<annotated root> so `import _moirai_prov` resolves in every process. "
                                       "Not counted in the annotate verdict: the integrate stage checks it."})
    text = "\n".join(p.read_text(errors="replace") for p in _files(dst, {".py", ".c", ".cc", ".cpp", ".cxx"} | YAML_EXT) if p.name != "_moirai_prov.py")
    for a in spec["activities"]:
        n = re.sub(r"\W", "_", a["name"])
        v.check(f"inserted:{a['name']}", repr(a["name"]) in text or n in text or (a.get("mode") == "yaml_step" and a["name"] in text), "not in the annotated code", "re-run annotate_apply")
    used = {e["type"] for a in spec["activities"] for _, e in _entities(a)}
    unused = sorted({t["type"] for t in spec["entity_types"]} - used)
    v.check("types_used", not unused, f"never used: {unused}", "relate them to an activity or drop them")
    return deferred


def register(mcp):
    @mcp.tool()
    def annotate_spec(pipeline: str, spec: dict) -> dict:
        """Check and save the provenance spec. Use after agreeing it with the user. spec: {scientific_artifacts: [types the user agreed], entity_types: [{type, role, description, id_scheme}],
        activities: [...], entry: file with main (C/C++)}. role: input|output|intermediate|parameter|reference. store: local_disk|parallel_fs|memory|network|...
        An activity: {file, name, mode, <where>, used|generated|invalidated|updated: [entity], relations: [edge], capture?}. An entity: {type, key|key_expr, store, uri|uri_expr, when, attributes?}; key_expr is
        code over the function's parameters (Python: also `result`, except in used and statement); when is code, the edge exists only if it is true. invalidated is moirai's relation
        for a delete, updated for an in-place change. capture (Python): false, or {auto?, output?, inputs?: {label: expression of the arguments, or of the locals for a statement},
        outputs?: {label: expression}}; outputs is for a hook that returns None and keeps its result on self: each expression is evaluated AFTER the call over the arguments, `self` and `result`
        (a statement: its locals), guarded, and becomes one <activity>.output entity name=value (in addition to the return value), which is what an outputs query reads; example
        capture: {outputs: {"final": "int(self.stdout.split(':')[-1])"}}. mode and <where>: wrap (default) {function: "Class.method"}; patch {target: "ServerTask.start", params?: [names]} reassigns the
        method wrapped, also an inherited one; subclass {base, method, class_name?, rebind?, params?} inserts a subclass whose method wraps super(); statement {anchor: text in one statement,
        at?: before|after, occurrence?: 1, in?: function} adds a one-shot activity whose keys read the surrounding locals. yaml_step {file: "biotox.yaml", step: "af3_infer", params?: [Maestro
        names a parameter generator makes], shell_vars?: [shell names set outside the cmd], record_on_failure?: false} records used and generated when a shell step of a Maestro YAML ENDS (a
        step that exits non-zero records nothing unless record_on_failure), for AlphaFold or Rosetta commands that no Python or C function wraps. Its entities take shell text, not code: key and
        uri may hold Maestro variables $(SEQ) $(SEED) $(<step>.workspace) and shell variables ${CIF_FILE} (so both sides of a hop get the SAME type and key), no double quote, backtick or
        $(command); an entity on a file store is recorded only if its uri exists (or its `when` holds: the arguments of [ ], such as -f "$CIF_FILE"; or exists: false), so an early exit 0 records
        nothing. An edge between entities: {relation: contains|derived_from|
        revision_of|part_of|specialization_of|alternate_of|depends_on, subject: entity, object: entity, when?}. patch, subclass, statement and relations are Python only; yaml_step takes
        used and generated only. A scientific artifact may be generated only by yaml_step activities. Example, the driver
        side of an RPC: {file: "tasks.py", mode: "patch", target: "ServerTask.start", params: ["self", "seq_id", "model"], name: "submit_inference", generated: [{type: "inference_request",
        key_expr: "seq_id + '/' + model", store: "network"}]}. Example, a shell step: {file: "biotox.yaml", mode: "yaml_step", step: "af3_infer", name: "af3_infer", used: [{type: "msa_input",
        key: "$(TARGET)/$(PEP_ID)/seed-$(SEED)_sample-$(SAMPLE)", uri: "$(af3_msa.workspace)/x_data.json", store: "parallel_fs"}], generated: [{type: "predicted_complex", key: "...", uri: "${CIF}",
        store: "parallel_fs"}]}. Returns {status, problems}, or {status, entity_types, activities}."""
        spec = json.loads(spec) if isinstance(spec, str) else spec
        c = P.load(pipeline)
        bad = _check_spec(spec, Path(P.source_of(c)))
        if bad:
            return {"status": "error", "problems": bad}
        types = spec.get("entity_types", [])
        (P.work(c) / "spec.json").write_text(json.dumps(spec, indent=1))
        P.record(pipeline, STAGE, outputs={"spec": spec, "summary": f"{len(types)} entity type(s), {len(spec['activities'])} activities"})
        return {"status": "ok", "entity_types": len(types), "activities": len(spec["activities"])}

    @mcp.tool()
    def annotate_apply(pipeline: str) -> dict:
        """Copy the app to the provenance source tree (<session>/provenance/source) and insert the saved spec. Use after annotate_spec; safe to repeat (it starts over from the source).
        A yaml_step block is written into the copy of the Maestro YAML (the source YAML is untouched), and the generated _moirai_prov.py gets a command-line entry the block calls.
        Returns {status, annotated, files, missing, unresolved, diff}; unresolved lists key expressions that name something not in scope."""
        c = P.load(pipeline)
        spec = P.stage(c, STAGE)["outputs"].get("spec")
        if not spec:
            return {"status": "error", "error": "no spec: call annotate_spec first"}
        src, dst = Path(P.source_of(c)), P.work(c) / "source"
        shutil.rmtree(dst, ignore_errors=True)
        shutil.copytree(src, dst, ignore=SKIP, symlinks=True)
        by_file, python, missing, unresolved = _annotate(dst, spec)
        diff = _diff(src, dst)
        (P.work(c) / "annotation.diff").write_text(diff)
        P.record(pipeline, STAGE, outputs={"annotated": str(dst), "files": sorted(by_file), "missing": missing, "unresolved": unresolved, "languages": ["python"] if python else ["c"]},
                 note=f"annotated {len(by_file)} file(s)")
        return {"status": "ok" if not missing else "error", "annotated": str(dst), "files": sorted(by_file), "missing": missing, "unresolved": unresolved, "diff": diff[:12000]}

    @mcp.tool()
    def annotate_preview(spec: dict, files: dict, run: str = "", run_steps: str = "", variables: dict = None, step_env: dict = None) -> dict:
        """Try a spec on a few files in a temporary directory, with no pipeline. Use to check a pattern (a patched method, a subclass, a delete, a statement, a conditional edge, a Maestro
        shell step) before annotate_spec, and to reproduce a mis-generated pattern. spec: as annotate_spec. files: {relative path: text}. run: a Python file among them to execute with a
        fake moirai that records what was related; it runs in the temp copy. run_steps: comma-separated names of yaml_step steps in an annotated YAML, run in order with bash in one empty
        directory against the fake moirai (the wrapper really runs: its exit code, early exits and skipped records can be read). variables: {Maestro name: value} substituted into those steps,
        for example {"SEQ": "t1", "af3_msa.workspace": "."}. step_env: extra environment for them, for example {"MOIRAI_PYTHON": "/bin/false"} to see that a broken moirai changes nothing.
        Returns {status, files: annotated text, missing, unresolved, events: [{activity, relations: [[REL, type, key]]}],
        links: [[REL, subject type, key, object type, key]], captured: [{activity, relation, type, value}] (the .input, .output and .attribute entities, as name=value), rc, stderr, step_rcs, step_runs} or {status: error, problems}."""
        spec = json.loads(spec) if isinstance(spec, str) else spec
        files = json.loads(files) if isinstance(files, str) else files
        variables = json.loads(variables) if isinstance(variables, str) else (variables or {})
        step_env = json.loads(step_env) if isinstance(step_env, str) else (step_env or {})
        unsafe = [r for r in list(files) + ([run] if run else []) if not _safe(r)]
        if unsafe:
            return {"status": "error", "problems": [f"path must be relative and stay inside: {r}" for r in unsafe]}
        with tempfile.TemporaryDirectory() as d:
            root, dst, fake = Path(d) / "app", Path(d) / "annotated", Path(d) / "fake"
            for rel, text in files.items():
                (root / rel).parent.mkdir(parents=True, exist_ok=True)
                (root / rel).write_text(text)
            bad = _check_spec(spec, root)
            if bad:
                return {"status": "error", "problems": bad}
            shutil.copytree(root, dst)
            by_file, python, missing, unresolved = _annotate(dst, spec)
            out = {"status": "ok" if not missing else "error", "files": {rel: (dst / rel).read_text() for rel in sorted(by_file)}, "missing": missing, "unresolved": unresolved}
            if run:
                if not (dst / run).is_file():
                    return {**out, "status": "error", "problems": [f"run: no file {run}"]}
                fake.mkdir()
                (fake / "moirai.py").write_text(FAKE_MOIRAI)
                got = Path(d) / "events.json"
                env = {"PATH": os.environ.get("PATH", ""), "HOME": d, "MOIRAI_FAKE_OUT": str(got)}
                r = subprocess.run([sys.executable, "-I", "-c", RUNNER, str(dst / run), str(dst), str(fake)], cwd=str(dst), capture_output=True, text=True, timeout=60, env=env)
                seen = json.loads(got.read_text()) if got.is_file() else {"events": [], "links": []}
                out.update({"rc": r.returncode, "stderr": r.stderr[-600:], "events": seen["events"], "links": seen["links"], "captured": seen.get("captured", [])})
            if run_steps:
                ran = _run_steps(dst, d, run_steps, variables, step_env)
                if ran.get("status") == "error":
                    return {**out, **ran}
                out.update(ran)
            return out

    @mcp.tool()
    def annotate_diagram(pipeline: str, budget: int = 60, collapse: bool = True) -> dict:
        """Draw what was annotated as an entity-type relationship diagram, for the annotate gate. Use after annotate_apply and a passing annotate_validate, and embed the result in
        the ask_user context. Reads the applied spec of the pipeline and writes <session>/provenance/annotation_diagram.md. Entity types are nodes grouped as scientific artifact /
        input / intermediate / parameter / reference / network / output; activities are nodes grouped under their source file, with how they are attached (wrap function, patch
        target, subclass base.method, statement anchor, yaml_step step); edges are used, generated, invalidated (red dotted), updated, relations between entities (blue), and conditional `when`
        edges (dashed, labelled). budget: the most edges to draw with labels; beyond it unconditional used/generated labels are dropped (and the result says so). collapse: draw
        types of one family (model_1 .. model_5, <seq_id> placeholders) as one node with a note. Counts come from the spec. Returns {status, path, mermaid, markdown, counts,
        collapsed, notes, labels_dropped, outline, non_wrap, marks} or {status: error, error}."""
        c = P.load(pipeline)
        o = P.stage(c, STAGE)["outputs"]
        if not o.get("annotated") or not o.get("spec"):
            return {"status": "error", "error": "annotate_apply has not run: there is no applied spec to draw", "fix": "annotate_spec, then annotate_apply"}
        d = _diagram(o["spec"], budget, collapse)
        md = _diagram_markdown(d)
        path = P.work(c) / "annotation_diagram.md"
        path.write_text(md + "\n")
        P.record(pipeline, STAGE, outputs={"diagram": str(path), "diagram_counts": d["counts"]})
        return {"status": "ok", "path": str(path), "markdown": md, **d}

