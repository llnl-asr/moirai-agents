def describe_type(t, spec):
    """An entity type's description, with what the spec knows about it: its attributes and the activities expected to produce and use it."""
    name, acts = t["type"], spec.get("activities", [])
    made = sorted({a.get("name", "?") for a in acts for k in ("generated", "updated") for e in a.get(k, []) if e.get("type") == name})
    used = sorted({a.get("name", "?") for a in acts for e in a.get("used", []) if e.get("type") == name})
