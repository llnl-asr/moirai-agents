"""Run pipeline stages 5 and 6: run the annotated app under moirai-service, first a smoke run, then the baseline, watched live on the Dashboard.
Two ways to launch: a command (wrapped in one script), or batch mode: the app's own generated `flux batch` script (run.sh) is rewritten with a moirai preamble."""
import json
import math
import os
import re
import shlex
from pathlib import Path

from moirai_agents.core import jobs as J
from moirai_agents.core import pipeline as P
from moirai_agents.core import provtrace as T

STAGES = ("moirai_smoke", "baseline")
DRAIN_RE = re.compile(r'^\s*flux resource drain\s+"?\$\{?crit_ranks\}?"?\s*$')
NUMN_RE = re.compile(r'^\s*num_nodes=\$\(\(\s*num_nodes\s*-\s*num_crit_nodes\s*\)\)\s*$')
CRIT_RE = re.compile(r'^\s*crit_nodes=')
FLUX_HDR_RE = re.compile(r'^#flux:')


def _shm(pid, stage):
    return f"/moirai-agents-{pid[-20:]}-{stage}".replace(".", "-")


def _script(env, pid, stage, log, data_dir, command, launcher, nodes):
    q = shlex.quote
    svc_all = f"flux run -N {nodes} --tasks-per-node=1 " if nodes > 1 else ""
    shm = _shm(pid, stage)
    return f"""set -uo pipefail
source {q(env)}
export MOIRAI_LOG_FILE={q(log)}
export MOIRAI_DATA_DIR={q(data_dir)}
export MOIRAI_SERVICE_SHM={shm}
export MOIRAI_PC_BLOCKS=${{MOIRAI_PC_BLOCKS:-16}}
export MOIRAI_PC_FLUSH_MS=${{MOIRAI_PC_FLUSH_MS:-250}}   # how fresh the live view is
stop() {{ trap - EXIT TERM INT; {svc_all}moirai-service stop; }}
trap stop EXIT
trap 'exit 143' TERM INT
{svc_all}moirai-service start
for _ in $(seq 100); do [ -s "/dev/shm$MOIRAI_SERVICE_SHM" ] && break; sleep 0.1; done
[ -s "/dev/shm$MOIRAI_SERVICE_SHM" ] || echo "moirai-service ring not visible here: events may go to spill files" >&2
{launcher} {command}
"""


# ---------------------------------------------------------------- batch mode

_PRE_A = r'''# ===== moirai preamble (generated by moirai_run; the original run.sh follows unchanged) =====
source @ENV@
export MOIRAI_LOG_FILE=@LOG@
export MOIRAI_DATA_DIR=@DATA@
export MOIRAI_SERVICE_SHM="@SHM@-$(printf %s "${FLUX_JOB_ID:-$$}" | tr -c 'A-Za-z0-9' '_')"
export MOIRAI_PC_BLOCKS=${MOIRAI_PC_BLOCKS:-16}
export MOIRAI_PC_FLUSH_MS=${MOIRAI_PC_FLUSH_MS:-250}
# moirai-service is a wrapper around dftracer_service; its build-time default path may be gone: resolve a real one
_ms_bin=$(command -v moirai-service || true)
[ -n "$_ms_bin" ] || { echo "moirai: moirai-service is not on PATH after sourcing moirai_env.sh" >&2; exit 1; }
_ms_dir=$(dirname "$(readlink -f "$_ms_bin")")
_ms_def=$(moirai-service --help 2>&1 | grep -o '/[^[:space:]"]*dftracer_service' | head -1)
if [ -n "${MOIRAI_DFTRACER_SERVICE:-}" ] && [ -x "$MOIRAI_DFTRACER_SERVICE" ]; then :
elif [ -n "$_ms_def" ] && [ -x "$_ms_def" ]; then :
else
  for _c in @SVCBIN@ "$_ms_dir"/../lib/python*/site-packages/dftracer/bin/dftracer_service "$_ms_dir"/dftracer_service "$(command -v dftracer_service || true)"; do
    if [ -n "$_c" ] && [ -x "$_c" ]; then export MOIRAI_DFTRACER_SERVICE="$_c"; break; fi
  done
  [ -x "${MOIRAI_DFTRACER_SERVICE:-}" ] || { echo "moirai: no usable dftracer_service (default ${_ms_def:-none} is gone); pass dftracer_service=" >&2; exit 1; }
fi
echo "moirai: moirai-service=$_ms_bin dftracer_service=${MOIRAI_DFTRACER_SERVICE:-$_ms_def} shm=$MOIRAI_SERVICE_SHM"
# ===== end moirai preamble =====
'''

_PRE_B = r'''# ===== moirai services (after the drain: the launch node is drained, so only it gets a plain start) =====
_svc_dir=@SVCDIR@
mkdir -p "$_svc_dir"
_hl() { tr ' ,' '\n\n' | sed '/^$/d'; }
_hosts_all=$(flux hostlist -e local | _hl)
_hosts_crit=$(flux hostlist -e "${crit_nodes}" | _hl)
_hosts_sched=$(printf '%s\n' "$_hosts_all" | grep -vxF -f <(printf '%s\n' "$_hosts_crit") || true)
echo "MOIRAI_HOSTS launch=$(echo $_hosts_crit) sched=$(echo $_hosts_sched)"
_svc_jobs=""
_moirai_stop_all() {
  trap - EXIT TERM INT
  for _h in $_hosts_sched; do flux run -N1 -n1 --requires="host:$_h" moirai-service stop || echo "moirai: stop failed on $_h" >&2; done
  [ -z "$_svc_jobs" ] || flux cancel $_svc_jobs 2>/dev/null || true
  for _h in $_hosts_crit; do moirai-service stop || echo "moirai: stop failed on $_h" >&2; done
}
trap _moirai_stop_all EXIT
trap 'exit 143' TERM INT
if [ -n "$_hosts_crit" ]; then
  ( setsid nohup moirai-service start > "$_svc_dir/start-$(hostname).out" 2>&1 < /dev/null & )
fi
for _h in $_hosts_sched; do
  _j=$(flux submit -N1 -n1 --requires="host:$_h" --output="$_svc_dir/start-$_h.out" --error="$_svc_dir/start-$_h.err" moirai-service start)
  [ -n "$_j" ] || { echo "moirai: could not submit the service on $_h" >&2; exit 1; }
  _svc_jobs="$_svc_jobs $_j"
done
if [ -n "$_hosts_crit" ]; then
  for _ in $(seq 200); do [ -s "/dev/shm$MOIRAI_SERVICE_SHM" ] && break; sleep 0.3; done
  [ -s "/dev/shm$MOIRAI_SERVICE_SHM" ] || { echo "moirai: ring $MOIRAI_SERVICE_SHM not visible on the launch node $(hostname)" >&2; exit 1; }
fi
for _h in $_hosts_sched; do
  _ok=0
  for _ in $(seq 30); do
    if flux run -N1 -n1 --requires="host:$_h" test -s "/dev/shm$MOIRAI_SERVICE_SHM"; then _ok=1; break; fi
    sleep 2
  done
  [ "$_ok" = 1 ] || { echo "moirai: ring $MOIRAI_SERVICE_SHM not visible on $_h (see $_svc_dir/start-$_h.*)" >&2; exit 1; }
done
echo "MOIRAI_SERVICES_READY launch=$(echo $_hosts_crit) sched=$(echo $_hosts_sched)"
# ===== end moirai services =====
'''


def build_batch(run_sh, env, log, data_dir, svc_dir, shm, svcbin=""):
    """Insert the moirai preamble into the text of a generated run.sh. Raises ValueError (what, and the fix) when run.sh does not have the expected shape."""
    lines = run_sh.splitlines()
    if not lines or not lines[0].startswith("#!"):
        raise ValueError("run.sh has no shebang on line 1: not the shape gen_launch_script.py writes; extend build_batch after reading it")
    last_hdr = None
    for i, ln in enumerate(lines):
        if FLUX_HDR_RE.match(ln):
            last_hdr = i
        elif ln.strip() and not ln.startswith("#"):
            break
    if last_hdr is None:
        raise ValueError("no `#flux:` header lines before the first command: this is not a flux batch script")
    drains = [i for i, ln in enumerate(lines) if DRAIN_RE.match(ln)]
    if len(drains) != 1:
        raise ValueError(f'expected exactly one `flux resource drain "${{crit_ranks}}"` line, found {len(drains)}: run.sh changed shape (or has no launch node); read it and adjust the insertion point')
    d = drains[0]
    if not any(NUMN_RE.match(ln) for ln in lines[:d]):
        raise ValueError("`num_nodes=$((num_nodes - num_crit_nodes))` not found before the drain line: run.sh changed shape")
    if not any(CRIT_RE.match(ln) for ln in lines[:d]):
        raise ValueError("`crit_nodes=` not found before the drain line: the service start needs the launch host names")
    if any(re.match(r'^\s*trap\s', ln) for ln in lines):
        raise ValueError("run.sh already sets a trap: the moirai EXIT trap would replace it; merge them by hand")
    q = shlex.quote
    a = _PRE_A.replace("@ENV@", q(env)).replace("@LOG@", q(log)).replace("@DATA@", q(data_dir)).replace("@SHM@", shm).replace("@SVCBIN@", q(svcbin) if svcbin else '""')
    b = _PRE_B.replace("@SVCDIR@", q(svc_dir))
    out = lines[:last_hdr + 1] + a.splitlines() + lines[last_hdr + 1:d + 1] + b.splitlines() + lines[d + 1:]
    return "\n".join(out) + "\n"


def build_wrapper(script, queue, minutes):
    """The wrapper job: load mpifileutils (dbcast must be on PATH of the submitting shell), flux batch, flux watch, return the batch job's code."""
    q = shlex.quote
    qopt = f" --queue {q(queue)}" if queue else ""
    cmd = f"flux batch -t {minutes}m{qopt} {q(script)}"
    text = f"""set -uo pipefail
if ! type module >/dev/null 2>&1; then
  for f in /etc/profile.d/z00_lmod.sh /etc/profile.d/lmod.sh /usr/share/lmod/lmod/init/bash; do [ -r "$f" ] && . "$f" && break; done
fi
module load mpifileutils/0.11.1 || {{ echo "wrapper: module load mpifileutils/0.11.1 failed" >&2; exit 1; }}
command -v dbcast >/dev/null || {{ echo "wrapper: dbcast is not on PATH after the module load: the batch job would abort" >&2; exit 1; }}
jobid=$({cmd}) || {{ echo "wrapper: flux batch failed to submit" >&2; exit 1; }}
echo "wrapper: submitted batch job $jobid"
trap 'echo "wrapper: stopped, cancelling $jobid" >&2; flux cancel "$jobid"; exit 143' TERM INT
flux watch "$jobid" &
wait $!
flux job status -v "$jobid"; rc=$?
if [ "$rc" -ne 0 ]; then echo "wrapper: batch job $jobid FAILED with return code $rc" >&2; exit "$rc"; fi
echo "wrapper: batch job $jobid finished with return code 0"
"""
    return text, cmd


def _plan(pipeline, stage, batch_script, run_sh_text, queue, limit, env_file, traces_dir, data_dir, dftracer_service):
    if pipeline:
        c = P.load(pipeline)
        integ = P.stage(c, "integrate")["outputs"]
        env_file = env_file or integ.get("env", "")
        data_dir = data_dir or integ.get("annotated", "")
        traces_dir = traces_dir or str(P.work(c) / "traces" / stage)
    if not env_file or not traces_dir:
        return {"status": "error", "error": "need a pipeline (integrate done) or env_file and traces_dir"}
    text = run_sh_text
    if not text:
        try:
            text = Path(os.path.expanduser(batch_script)).read_text()
        except OSError as e:
            return {"status": "error", "error": f"cannot read batch_script: {e}"}
    td = Path(traces_dir)
    tag = (pipeline or "sandbox")
    try:
        script = build_batch(text, env_file, str(td / "raw" / "prov"), data_dir or str(td), str(td / "service"), _shm(tag, stage), dftracer_service)
    except ValueError as e:
        return {"status": "error", "error": str(e)}
    run_path = str(td / "run-moirai.sh")
    minutes = max(1, math.ceil((limit or 1800) / 60))
    wrapper, cmd = build_wrapper(run_path, queue, minutes)
    warnings = []
    if data_dir and data_dir not in text:
        warnings.append(f"run.sh never mentions the annotated tree {data_dir}: it may run the original, unannotated source")
    if "dbcast" in text and "mpifileutils" not in text:
        warnings.append("run.sh uses dbcast: the wrapper loads mpifileutils/0.11.1 before flux batch")
    m = re.search(r"^#flux: --nodes[ =](\d+)", text, re.M)
    return {"status": "ok", "script": script, "script_path": run_path, "wrapper": wrapper, "submit_command": cmd, "minutes": minutes,
            "nodes": int(m.group(1)) if m else None, "warnings": warnings, "inserted": ["after the last #flux: header line", "after the flux resource drain line"]}


def _start(pipeline, stage, command, launcher, nodes, data_dir, wait, limit, batch_script="", queue="", dftracer_service="", queue_wait=3600):
    c = P.load(pipeline)
    P.require_ready(c, stage)
    integ, cmd = P.stage(c, "integrate")["outputs"], command or c["command"]
    if not integ.get("env"):
        return {"status": "error", "error": "the integrate stage has not written moirai_env.sh"}
    tdir = P.work(c) / "traces" / stage / "raw"     # dfdashboard's run layout: <root>/<run>/raw/*.pfw.gz
    tdir.mkdir(parents=True, exist_ok=True)
    wd = integ["annotated"]
    extra = {}
    if batch_script:
        pl = _plan(pipeline, stage, batch_script, "", queue, limit, "", "", data_dir, dftracer_service)
        if pl["status"] != "ok":
            return pl
        rp = Path(pl["script_path"])
        rp.write_text(pl["script"])
        rp.chmod(0o755)
        script, cmd, launcher = pl["wrapper"], f"flux batch {batch_script}", "flux batch"
        nodes = pl["nodes"] or nodes
        extra = {"batch_script": batch_script, "run_script": str(rp), "submit_command": pl["submit_command"], "warnings": pl["warnings"]}
        job_limit = int(limit) + int(queue_wait)       # the queue wait is not part of the batch time limit
    else:
        script = _script(integ["env"], pipeline, stage, str(tdir / "prov"), data_dir or wd, cmd, launcher, nodes)
        job_limit = limit
    j = J.start(pipeline, stage, stage.replace("_", "-"), script, wd, limit=job_limit)
    P.set_dashboard(pipeline, str(tdir), live=True)
    P.record(pipeline, stage, status="running", outputs={"job": j["id"], "traces": str(tdir), "command": cmd, "launcher": launcher, "nodes": nodes, **extra}, note=f"running under moirai: {cmd}")
    r = J.wait(pipeline, j["id"], wait)
    return {"status": r["status"], "job": j["id"], "rc": r["rc"], "elapsed": r["elapsed"], "traces": str(tdir), "log_tail": r.get("log_tail", "")[-2500:],
            "note": "the Dashboard tab shows the provenance as it arrives", **extra}


def _hosts_of(files, hosts):
    """Group trace files by host. With a known host list a file belongs to the host whose name is one of its '-'/'_' separated tokens; without, the second token
    of the file name is the best guess (UNVERIFIED against dftracer's naming: pass hosts)."""
    out = {}
    for f in files:
        b = os.path.basename(f)
        toks = re.split(r"[-_.]", b)
        h = next((t for t in toks if t in hosts), None) if hosts else (toks[1] if len(toks) > 2 else "unknown")
        out.setdefault(h or "unknown", []).append(f)
    return {h: {"files": len(fs), "spill_only": all("-spill" in os.path.basename(x) for x in fs)} for h, fs in sorted(out.items())}


def register(mcp):
    @mcp.tool()
    def moirai_smoke_run(pipeline: str, command: str = "", launcher: str = "", wait: int = 600, limit: int = 1800, batch_script: str = "", queue: str = "",
                         dftracer_service: str = "", queue_wait: int = 3600) -> dict:
        """Run the annotated app on the small test under moirai-service. Use after integrate. It stops the service however the app ends; limit: seconds before it is
        stopped (batch mode: also the `flux batch -t` time, in minutes). The Dashboard tab follows it live.
        batch_script: path of the app's generated `flux batch` run.sh: then command/launcher are ignored, run-moirai.sh is written next to the traces, and a wrapper job
        submits it (see moirai_batch_plan: ALWAYS show that to the user first). queue: flux queue for batch mode. dftracer_service: real dftracer_service binary to use
        when moirai-service's built-in default is gone. queue_wait: extra seconds the wrapper may wait in the queue.
        Returns {status, job, rc, elapsed, traces, log_tail} (+ run_script, submit_command, warnings in batch mode)."""
        return _start(pipeline, "moirai_smoke", command, launcher, 1, "", wait, limit, batch_script, queue, dftracer_service, queue_wait)

    @mcp.tool()
    def moirai_baseline_run(pipeline: str, command: str = "", launcher: str = "", nodes: int = 1, data_dir: str = "", wait: int = 30, limit: int = 3600,
                            batch_script: str = "", queue: str = "", dftracer_service: str = "", queue_wait: int = 3600) -> dict:
        """Start the real baseline run under moirai-service, in the background, on what the user approved at the gate. command: the full run. launcher: e.g. 'flux run -N4 -n32'.
        nodes: one service starts per node. data_dir: where its I/O is traced. limit: seconds before it is stopped. batch_script, queue, dftracer_service, queue_wait: batch
        mode, as in moirai_smoke_run (command/launcher/nodes ignored). The Dashboard tab shows events as they appear. Returns {status, job, traces}: watch with moirai_run_status."""
        return _start(pipeline, "baseline", command, launcher, nodes, data_dir, wait, limit, batch_script, queue, dftracer_service, queue_wait)

    @mcp.tool()
    def moirai_batch_plan(batch_script: str = "", queue: str = "", limit: int = 1800, pipeline: str = "", stage: str = "moirai_smoke", run_sh_text: str = "",
                          env_file: str = "", traces_dir: str = "", data_dir: str = "", dftracer_service: str = "") -> dict:
        """DRY RUN of batch mode: starts and writes nothing. Returns the generated run-moirai.sh, the wrapper script and the exact submit command, for the user to read
        before moirai_smoke_run/moirai_baseline_run. Use before every batch submission. batch_script: path of run.sh (or run_sh_text: its text). pipeline+stage: take the
        moirai_env.sh, annotated tree and traces dir from the pipeline (else give env_file and traces_dir). limit: seconds, becomes `flux batch -t <minutes>m`.
        queue: flux queue. Errors (status=error) when run.sh does not have the expected shape: no #flux: header, not exactly one drain line, no num_nodes adjustment, an existing trap.
        Returns {status, script, script_path, wrapper, submit_command, minutes, nodes, warnings, inserted} or {status: error, error}."""
        return _plan(pipeline, stage, batch_script, run_sh_text, queue, limit, env_file, traces_dir, data_dir, dftracer_service)

    @mcp.tool()
    def moirai_trace_hosts(traces: str = "", files: list = None, hosts: list = None) -> dict:
        """Group moirai trace files by host and say which hosts only have spill files (no service was reachable there). Use after a multi-node run, or to test names.
        traces: trace dir/glob, or files: a list of file names. hosts: the expected host names (the run log's MOIRAI_HOSTS line); without them the host is guessed from the name.
        Returns {hosts: {host: {files, spill_only}}, spill_only_hosts, missing_hosts}."""
        fl = list(files or []) or T.expand(traces)
        hs = _hosts_of(fl, set(hosts or []))
        return {"hosts": hs, "spill_only_hosts": [h for h, v in hs.items() if v["spill_only"]], "missing_hosts": sorted(set(hosts or []) - set(hs))}

    @mcp.tool()
    def moirai_run_status(pipeline: str, stage: str) -> dict:
        """Follow a run: job state, log tail and what the trace holds so far (readable while the run is going). Use while it runs, to report progress or spot a stall.
        Returns {job, rc, elapsed, counts, log_tail}."""
        o = P.stage(P.load(pipeline), stage)["outputs"]
        j = J.get(pipeline, o["job"], 2000)
        return {"job": j["id"], "status": j["status"], "rc": j["rc"], "elapsed": j["elapsed"], "timed_out": j.get("timed_out", False), "counts": T.read(o["traces"]).counts(), "log_tail": j["log_tail"]}

    @mcp.tool()
    def moirai_run_stop(pipeline: str, stage: str) -> dict:
        """Stop a run (the service is stopped and the trace closed; in batch mode the wrapper cancels the batch job and its trap stops the services). Use when the user asks,
        or the run is clearly stuck. Returns {status, id, stopped}."""
        return J.stop(pipeline, P.stage(P.load(pipeline), stage)["outputs"]["job"])

    @mcp.tool()
    def moirai_validate(pipeline: str, stage: str) -> dict:
        """Validate a moirai run: exit 0, a trace from the service and not spill files (per host in a multi-node run), activities and entities recorded, no dangling edge, and every
        entity type in the spec seen. stage: moirai_smoke|baseline. Use after the job ended. Returns the verdict {status, failed, unknown, passed, total}."""
        c = P.load(pipeline)
        o = P.stage(c, stage)["outputs"]
        v = P.Verdict(stage)
        if not v.check("ran", bool(o.get("job")), "the run has not started", "start the run"):
            return P.finish_validation(pipeline, v)
        j = J.get(pipeline, o["job"], 400000)
        if j["status"] == "running":
            v.inconclusive("finished", f"still running after {j['elapsed']} s")
            return P.finish_validation(pipeline, v)
        v.check("exit_0", j["rc"] == 0, f"rc={j['rc']}{' (timed out)' if j.get('timed_out') else ''}: {j.get('log_tail', '')[-300:]}",
                "raise limit if it timed out; otherwise compare with the smoke stage: did the annotation break it?")
        files = T.expand(o["traces"])
        v.check("trace", bool(files), "no trace file", "read the service log next to the trace prefix")
        m = re.search(r"MOIRAI_SERVICES_READY launch=(.*?) sched=(.*)", j.get("log_tail", ""))
        hosts = sorted(set((m.group(1) + " " + m.group(2)).split())) if m else []
        hh = _hosts_of(files, set(hosts)) if files else {}
        spill = [h for h, x in hh.items() if x["spill_only"]]
        v.check("service_trace", not files or not spill, f"only spill files on {spill or 'all hosts'}: no service was reachable there", "check the service log (<traces>/../service/start-<host>.*); is /dev/shm big enough? same MOIRAI_SERVICE_SHM and host on start and app?")
        if hosts:
            lost = sorted(set(hosts) - set(hh))
            v.check("hosts_traced", not files or not lost, f"no trace file from {lost}", "that node ran no annotated process, or its service wrote elsewhere: see the service log on that host; the host-name guess in file names is unverified")
        g = T.read(o["traces"])
        n = g.counts()
        v.check("activities", n["activities"] > 0, f"{n['activities']} activities", "is the annotated code on the executed path? Is the app run from the annotated tree?")
        v.check("entities", n["entities"] > 0, f"{n['entities']} entities", "activities relate no entity: check the spec")
        v.check("no_dangling", n["dangling"] == 0, f"{n['dangling']} ids with no EH record", "every related entity must be declared")
        spec = P.stage(c, "annotate")["outputs"].get("spec") or {}
        seen = {e["type"] for e in g.entities.values()}
        missing = sorted({e["type"] for a in spec.get("activities", []) for e in a.get("used", []) + a.get("generated", [])} - seen)
        v.check("types_seen", not missing, f"never recorded: {missing}", "that code path did not run: use a test input that reaches it, or fix the spec")
        P.record(pipeline, stage, outputs={"counts": n, "hosts": hh, "summary": f"{n['activities']} activities, {n['entities']} entities, {n['edges']} edges, {len(hh)} host(s)"})
        return P.finish_validation(pipeline, v)
