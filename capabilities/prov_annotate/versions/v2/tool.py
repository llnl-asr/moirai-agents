def _text(value, names):
    return str(value(**names) if callable(value) else value)


def _ok(when, names):
    return when is None or bool(when(**names) if callable(when) else when)


def _entity(item, names):
    etype, key, store, uri = item[:4]
    return (etype, _text(key, names), getattr(moirai.Store, store), _text(uri, names))


def _bind(act, relation, items, names):
    """Relate each entity of items to the activity, unless its optional `when` is false."""
    for item in items:
        if _ok(item[4] if len(item) > 4 else None, names):
            act.relate(relation, _entity(item, names))


def _after(act, generated, invalidated, updated, relations, names):
    for relation, items in (("GENERATED", generated), ("INVALIDATED", invalidated), ("UPDATED", updated)):
        _bind(act, getattr(moirai.Relation, relation), items, names)
    for relation, subject, obj, when in relations:
        if _ok(when, names):
            moirai.relate(getattr(moirai.Relation, relation), _entity(subject, names), _entity(obj, names))


def activity(name, used=(), generated=(), invalidated=(), updated=(), relations=(), signature=None):
    """One moirai activity around each call; entity keys may read the call's arguments, and `result`. signature: the function whose
    parameters name the arguments, for a wrapper that takes *args."""
    def wrap(fn):
        sig = inspect.signature(signature or fn)

        @functools.wraps(fn)
        def call(*a, **k):
            start()
            try:
                names = dict(sig.bind(*a, **k).arguments)
            except TypeError:
                names = {}
            with moirai.Activity(name) as act:
                _bind(act, moirai.Relation.USED, used, names)
                result = fn(*a, **k)
                _after(act, generated, invalidated, updated, relations, {**names, "result": result})
                return result
        return call
    return wrap


def event(name, used=(), generated=(), invalidated=(), updated=(), relations=()):
    """A one-shot activity at a statement; its keys are closures over the surrounding locals. It has no duration."""
    start()
    with moirai.Activity(name) as act:
        _bind(act, moirai.Relation.USED, used, {})
        _after(act, generated, invalidated, updated, relations, {})
