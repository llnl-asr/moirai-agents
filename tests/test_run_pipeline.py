def test_package_lint_finds_what_would_tie_it_to_one_person(tmp_path, call):
    from moirai_agents.core import capstore
    import importlib.util
    spec = importlib.util.spec_from_file_location("rp", capstore.all_caps()["repro_package"][1] / "tool.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    pkg = tmp_path / "p"
    (pkg / "scripts").mkdir(parents=True)
    (pkg / "config.ini").write_text("OUTPUT_ROOT=/data\n")
    (pkg / "scripts" / "a.sh").write_text("echo /secret/session\n")
    found = m.lint(pkg, Path("/secret/session"))
    assert any("workspace path" in f for f in found) and any("does not source" in f for f in found)
    (pkg / "scripts" / "a.sh").write_text('source "$(dirname "$0")/lib_load_config.sh"\n')
    assert m.lint(pkg, Path("/secret/session")) == []
